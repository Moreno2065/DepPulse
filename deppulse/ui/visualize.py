def _safe_node_id(node: str) -> str:
    """Create a safe Mermaid/DOT node ID from a file path."""
    safe = node.replace("/", "_").replace(".", "_").replace("-", "_").replace("\\", "_")
    # Ensure it starts with a letter
    if safe and safe[0].isdigit():
        safe = "n" + safe
    return safe


def _escape_mermaid(text: str) -> str:
    """Escape text for safe embedding in Mermaid."""
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("<", "&lt;").replace(">", "&gt;")


def _escape_dot(text: str) -> str:
    """Escape text for safe embedding in DOT labels."""
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("<", "&lt;").replace(">", "&gt;")
