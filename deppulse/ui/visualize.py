# Mermaid
# ---------------------------------------------------------------------------


def render_mermaid_graph(
    graph: nx.DiGraph,
    *,
    title: str = "Dependency Graph",
    max_nodes: int = 200,
) -> str:
    """
    Render a dependency graph as a Mermaid flowchart.

    Groups nodes by language into subgraphs, colors edges by dependency kind,
    and marks high-risk nodes (high in-degree) with a warning style.
    """
    lines = ["flowchart LR", f'    %% {title} — generated by DepPulse']

    # Group nodes by language
    lang_groups: dict[str, list[str]] = {}
    node_lang: dict[str, Language] = {}
    node_risk: dict[str, bool] = {}

    for node in graph.nodes():
        data = graph.nodes.get(node, {})
        lang = data.get("language", Language.UNKNOWN)
        in_deg = graph.in_degree(node)
        high_risk = in_deg > 5  # heuristic: high fan-in = high risk

        node_lang[node] = lang
        node_risk[node] = high_risk

        suffix = data.get("suffix", Path(node).suffix)
        if suffix == ".py":
            lang_key = "Python"
        elif suffix == ".java":
            lang_key = "Java"
        elif suffix in (".kt", ".kts"):
            lang_key = "Kotlin"
        elif suffix in (".c", ".cpp", ".h", ".hpp", ".cc"):
            lang_key = "C/C++"
        else:
            lang_key = "Other"

        lang_groups.setdefault(lang_key, []).append(node)

    # Define subgraph IDs
    subgraph_ids: dict[str, str] = {}
    for i, key in enumerate(sorted(lang_groups.keys())):
        subgraph_ids[key] = f"sg{i}"

    # Declare subgraph styles
    color_map = {
        "Python": "#4B8BBE",
        "Java": "#B07219",
        "Kotlin": "#A18B00",
        "C/C++": "#F34B7D",
        "Other": "#AAAAAA",
    }

    shown = 0
    for lang_key, nodes in sorted(lang_groups.items()):
        sg_id = subgraph_ids[lang_key]
        _ = color_map.get(lang_key, "#AAAAAA")
        lines.append(f'    subgraph {sg_id} ["{lang_key}"]')
        for node in nodes[:max_nodes]:
            if shown >= max_nodes:
                break
            node_id = _safe_node_id(node)
            label = _escape_mermaid(Path(node).name)
            lines.append(f'        {node_id}["{label}"]')
            shown += 1
        lines.append("    end")

    # Add edge styles
    kind_colors = {
        "import": "#27ae60",
        "java_import": "#d35400",
        "kotlin_import": "#8e44ad",
        "include_local": "#2980b9",
        "include_system": "#7f8c8d",
    }

    # Draw edges
    for u, v, data in graph.edges(data=True):
        u_id = _safe_node_id(u)
        v_id = _safe_node_id(v)
        kind = data.get("kind", "unknown")
        _ = kind_colors.get(kind, "#95a5a6")
        lines.append(f"    {u_id} -.->|\"{kind}\"| {v_id}")

    if shown == 0:
        lines.append('    empty["(no nodes)"]')

    return "\n".join(lines)


def graph_to_mermaid(
    graph: nx.DiGraph,
    *,
    title: str = "Dependency Graph",
) -> str:
    """Alias for render_mermaid_graph for compatibility."""
    return render_mermaid_graph(graph, title=title)


