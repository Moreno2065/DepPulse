def render_dot_graph(
    graph: nx.DiGraph,
    *,
    title: str = "Dependency Graph",
) -> str:
    """
    Render a dependency graph as Graphviz DOT format.

    Nodes are colored by language, sized by in-degree, and high-risk
    nodes (many dependents) are highlighted in red.
    """
    lines = [
        "digraph dependencies {",
        f'    label="{_escape_dot(title)}";',
        '    labelloc="t";',
        '    rankdir=LR;',
        '    node [shape=box, style="rounded,filled", fontname=Helvetica, width=0.3];',
        '    edge [arrowsize=0.5];',
    ]

    for node in graph.nodes():
        data = graph.nodes.get(node, {})
        suffix = data.get("suffix", Path(node).suffix)
        in_deg = graph.in_degree(node)
        high_risk = in_deg > 5

        if suffix == ".py":
            color = "#4B8BBE"
        elif suffix == ".java":
            color = "#B07219"
        elif suffix in (".kt", ".kts"):
            color = "#A18B00"
        elif suffix in (".c", ".cpp", ".h", ".hpp", ".cc"):
            color = "#F34B7D"
        else:
            color = "#AAAAAA"

        if high_risk:
            color = "#e74c3c"

        label = _escape_dot(Path(node).name)
        lines.append(f'    "{_escape_dot(node)}" [label="{label}", fillcolor="{color}", color="#fff"];')

    for u, v, data in graph.edges(data=True):
        kind = data.get("kind", "unknown")
        lines.append(f'    "{_escape_dot(u)}" -> "{_escape_dot(v)}" [label="{kind}", color="#95a5a6", fontsize=8];')

    lines.append("}")
    return "\n".join(lines)


